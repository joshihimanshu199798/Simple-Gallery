package com.example.ui.theme

import androidx.compose.ui.graphics.Color

enum class GalleryLayoutStyle(
    val displayName: String,
    val tagLabel: String,
    val cardCornerDp: Int
) {
    BENTO_SHOWCASE("Bento Showcase", "STUDIO BENTO", 22),
    MAGAZINE_SPREAD("Magazine Spread", "EDITORIAL", 18),
    SWISS_STUDIO_GRID("Swiss Studio Grid", "SWISS GRID", 14),
    POLAROID_SCRAPBOOK("Polaroid Scrapbook", "ARCHIVAL", 20),
    CINEMA_FILMSTRIP("Cinema Filmstrip", "CINEMA", 20)
}

data class CompleteUiThemeSpec(
    val id: String,
    val name: String,
    val shortBadge: String,
    val isLight: Boolean,
    val layoutStyle: GalleryLayoutStyle,
    val background: Color,
    val backgroundSecondary: Color,
    val surface: Color,
    val surfaceVariant: Color,
    val primaryAccent: Color,
    val onPrimaryAccent: Color,
    val secondaryAccent: Color,
    val onSecondaryAccent: Color,
    val tertiaryAccent: Color,
    val textPrimary: Color,
    val textSecondary: Color,
    val borderStroke: Color,
    val topStripBackground: Color,
    val topStripText: Color,
    val captionOverlayBackground: Color,
    val dockBackground: Color
) {
    val modeLabel: String
        get() = if (isLight) "LIGHT" else "DARK"

    val bannerStatusText: String
        get() = "${name.uppercase()}  •  $modeLabel  •  $shortBadge"

    val heroPillText: String
        get() = "$modeLabel • $shortBadge"
}

